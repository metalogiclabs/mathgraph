#!/usr/bin/env python3
"""V58 prospective external capability compounding on untouched rows.

Frozen before any row >= 2628 is semantically inspected.

External streams
----------------
Phase A: Wrong Book 3000 rows 2628:2756 (128 problems)
Phase B: Wrong Book 3500 rows 2628:2756 (128 problems)

The upstream corpus commit and full-file SHA-256 digests are pinned.  The
workflow reads no published proof files and no verdict labels.

Truth boundary
--------------
The only terminal truth-bearing result is FALSE backed by an explicit finite
magma table that MathGraph independently checks:
  source identity holds for every assignment AND target identity fails at a
  concrete assignment.

cvc5 UNSAT is recorded only as PROOF_CANDIDATE/UNKNOWN.  It is never promoted
to TRUE in V58.  cvc5 UNKNOWN remains UNKNOWN.

Development
-----------
One continuous developer begins with an empty executable archive.

For each Phase-A problem:
  1. try all previously acquired finite magmas;
  2. try bounded one-cell descendants of the most reused acquired magmas;
  3. otherwise ask the frozen cvc5 finite-model constructor;
  4. independently verify and retain any finite countermodel.

The Phase-A archive is serialized and hashed, then reloaded.  Before any
Phase-B acquisition, the frozen archive is tested on the entire Phase-B
stream.  Phase B then continues with the same developer.

A cold Phase-B control invokes the identical cvc5 constructor independently
for every task, with no acquired archive and no descendant generator.

Causal tests
------------
* Cross-extension transfer must occur before Phase-B acquisition.
* At least one transferred consequence must have an individually essential
  learned ancestor: deleting that one acquired magma removes the consequence,
  and restoring it restores the consequence.
* At least one new verified capability must be generated by mutating an
  acquired capability, and must solve a task the cold cvc5 control did not
  solve under the identical time budget.
* Continuous development must invoke cvc5 fewer times than cold while
  producing at least as many verified FALSE consequences.
* Wrong terminal promotions must be zero by independent exhaustive checking.

A failed frozen gate is a scientific result.  Do not retune and re-report the
same rows as fresh evidence.
"""

