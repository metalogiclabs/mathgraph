def normalize_external_equation(text: str) -> str:
    out = str(text)
    for op in ("◇", "⋄", "·", "∙", "∗", "＊", "×"):
        out = out.replace(op, "*")
    return out


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def table_digest(table: Sequence[Sequence[int]]) -> str:
    normalized = _FMW.normalize_table(table)
    payload = json.dumps([list(row) for row in normalized], separators=(",", ":"), sort_keys=True)
    return hashlib.sha256(payload.encode()).hexdigest()


def load_fresh_slice(path: Path, expected_sha: str) -> tuple[list[dict], str]:
    data = path.read_bytes()
    digest = sha256_bytes(data)
    if digest != expected_sha:
        raise RuntimeError(f"dataset hash mismatch: {path}: {digest} != {expected_sha}")
    lines = data.decode("utf-8").splitlines()
    selected_lines = lines[FRESH_START:FRESH_START + FRESH_COUNT]
    if len(selected_lines) != FRESH_COUNT:
        raise RuntimeError(f"expected {FRESH_COUNT} rows from {FRESH_START}, got {len(selected_lines)}")
    rows = [json.loads(line) for line in selected_lines]
    return rows, digest


def stream_digest(rows: Sequence[dict]) -> str:
    payload = "\n".join(json.dumps(row, sort_keys=True, separators=(",", ":")) for row in rows)
    return hashlib.sha256(payload.encode()).hexdigest()


def independently_verified_false(problem: dict, table: Sequence[Sequence[int]]) -> bool:
    result = _FMW.check_finite_countermodel(
        normalize_external_equation(problem["equation1"]),
        normalize_external_equation(problem["equation2"]),
        table,
    )
    return bool(result.terminal_candidate_ok)


def symbolic_eval(term, op, env, tm):
    if term.name is not None:
        return env[term.name]
    return tm.mkTerm(
        Kind.APPLY_UF,
        op,
        symbolic_eval(term.left, op, env, tm),
        symbolic_eval(term.right, op, env, tm),
    )


def quantified_equation(eq, op, sort, tm, existential: bool, negate: bool):
    env = {name: tm.mkVar(sort, name.upper()) for name in eq.variables()}
    body = tm.mkTerm(
        Kind.EQUAL,
        symbolic_eval(eq.lhs, op, env, tm),
        symbolic_eval(eq.rhs, op, env, tm),
    )
    if negate:
        body = tm.mkTerm(Kind.NOT, body)
    variables = tm.mkTerm(Kind.VARIABLE_LIST, *[env[name] for name in eq.variables()])
    return tm.mkTerm(Kind.EXISTS if existential else Kind.FORALL, variables, body)


@dataclass
class ConstructorResult:
    status: str
    elapsed_ms: int
    table: tuple[tuple[int, ...], ...] | None = None
    n: int | None = None
    independently_verified: bool = False
    diagnostic: str = ""


def cvc5_construct(problem: dict, timeout_ms: int = CVC5_TIMEOUT_MS) -> ConstructorResult:
    tm = cvc5.TermManager()
    solver = cvc5.Solver(tm)
    solver.setLogic("ALL")
    solver.setOption("produce-models", "true")
    solver.setOption("finite-model-find", "true")
    solver.setOption("tlimit-per", str(timeout_ms))

    carrier = tm.mkUninterpretedSort("U")
    op_sort = tm.mkFunctionSort([carrier, carrier], carrier)
    op = tm.mkConst(op_sort, "m")

    source = _FMW.parse_equation(normalize_external_equation(problem["equation1"]))
    target = _FMW.parse_equation(normalize_external_equation(problem["equation2"]))

    solver.assertFormula(quantified_equation(source, op, carrier, tm, existential=False, negate=False))
    solver.assertFormula(quantified_equation(target, op, carrier, tm, existential=True, negate=True))

    started = time.monotonic()
    result = solver.checkSat()
    elapsed_ms = int(round((time.monotonic() - started) * 1000))

    if result.isUnknown():
        return ConstructorResult("UNKNOWN", elapsed_ms, diagnostic=str(result))
    if result.isUnsat():
        # Deliberately advisory in V58: no TRUE promotion.
        return ConstructorResult("PROOF_CANDIDATE", elapsed_ms, diagnostic="cvc5 UNSAT; not terminal in V58")

    elements = list(solver.getModelDomainElements(carrier))
    n = len(elements)
    if n < 1 or n > MAX_DOMAIN:
        return ConstructorResult(
            "MODEL_OUT_OF_SCOPE",
            elapsed_ms,
            n=n,
            diagnostic=f"model domain {n} outside frozen 1..{MAX_DOMAIN}",
        )

    index = {str(element): i for i, element in enumerate(elements)}
    rows: list[list[int]] = []
    for a in elements:
        row = []
        for b in elements:
            value = solver.getValue(tm.mkTerm(Kind.APPLY_UF, op, a, b))
            key = str(value)
            if key not in index:
                return ConstructorResult(
                    "MODEL_PARSE_FAILURE",
                    elapsed_ms,
                    n=n,
                    diagnostic=f"value {key!r} absent from model domain",
                )
            row.append(index[key])
        rows.append(row)

    table = _FMW.normalize_table(rows)
    verified = independently_verified_false(problem, table)
    if not verified:
        raise RuntimeError(f"independent MathGraph verifier rejected cvc5 SAT model for {problem['id']}")

    return ConstructorResult("VERIFIED_FALSE", elapsed_ms, table, n, True, "independently checked finite countermodel")


@dataclass
class Capability:
    cid: str
    table: tuple[tuple[int, ...], ...]
    acquired_on: str
    acquired_phase: str
    route: str
    parent_cid: str | None
    acquisition_index: int
    reuse_hits: int = 0

    @property
    def n(self) -> int:
        return len(self.table)

    def to_json(self) -> dict:
        return {
            "cid": self.cid,
            "table": [list(row) for row in self.table],
            "acquired_on": self.acquired_on,
            "acquired_phase": self.acquired_phase,
            "route": self.route,
            "parent_cid": self.parent_cid,
            "acquisition_index": self.acquisition_index,
            "reuse_hits": self.reuse_hits,
        }

    @classmethod
    def from_json(cls, row: dict) -> "Capability":
        return cls(
            cid=str(row["cid"]),
            table=_FMW.normalize_table(row["table"]),
            acquired_on=str(row["acquired_on"]),
            acquired_phase=str(row["acquired_phase"]),
            route=str(row["route"]),
            parent_cid=row.get("parent_cid"),
            acquisition_index=int(row["acquisition_index"]),
            reuse_hits=int(row.get("reuse_hits", 0)),
        )


def archive_payload(archive: Sequence[Capability]) -> dict:
    rows = [cap.to_json() for cap in archive]
    raw = json.dumps(rows, sort_keys=True, separators=(",", ":")).encode()
    return {"sha256": hashlib.sha256(raw).hexdigest(), "capabilities": rows}


def ranked_archive(archive: Sequence[Capability]) -> list[Capability]:
    return sorted(archive, key=lambda cap: (-cap.reuse_hits, cap.acquisition_index, cap.cid))


def archive_solvers(problem: dict, archive: Sequence[Capability]) -> list[Capability]:
    return [cap for cap in ranked_archive(archive) if independently_verified_false(problem, cap.table)]


def try_archive(problem: dict, archive: list[Capability], mutate_hits: bool = True) -> tuple[Capability | None, int]:
    checks = 0
    for cap in ranked_archive(archive):
        checks += 1
        if independently_verified_false(problem, cap.table):
            if mutate_hits:
                cap.reuse_hits += 1
            return cap, checks
    return None, checks


def one_cell_mutations(table: Sequence[Sequence[int]]) -> Iterable[tuple[tuple[int, ...], ...]]:
    base = _FMW.normalize_table(table)
    n = len(base)
    for i in range(n):
        for j in range(n):
            for value in range(n):
                if value == base[i][j]:
                    continue
                rows = [list(row) for row in base]
                rows[i][j] = value
                yield _FMW.normalize_table(rows)


def mutation_candidates(archive: Sequence[Capability]) -> Iterable[tuple[Capability, tuple[tuple[int, ...], ...]]]:
    seen = {cap.cid for cap in archive}
    for parent in ranked_archive(archive)[:MUTATION_PARENT_LIMIT]:
        made = 0
        for child in one_cell_mutations(parent.table):
            cid = table_digest(child)
            if cid in seen:
                continue
            seen.add(cid)
            yield parent, child
            made += 1
            if made >= MUTATIONS_PER_PARENT:
                break


def install(
    archive: list[Capability],
    table: Sequence[Sequence[int]],
    problem_id: str,
    phase: str,
    route: str,
    parent_cid: str | None = None,
) -> tuple[Capability, bool]:
    normalized = _FMW.normalize_table(table)
    cid = table_digest(normalized)
    for cap in archive:
        if cap.cid == cid:
            return cap, False
    cap = Capability(
        cid=cid,
        table=normalized,
        acquired_on=problem_id,
        acquired_phase=phase,
        route=route,
        parent_cid=parent_cid,
        acquisition_index=len(archive),
    )
    archive.append(cap)
    return cap, True


@dataclass
class SolveRecord:
    problem_id: str
    phase: str
    terminal: str
    route: str
    capability_cid: str | None
    parent_cid: str | None
    archive_checks: int
    mutation_checks: int
    cvc5_invocations: int
    cvc5_status: str | None
    cvc5_elapsed_ms: int
    installed: bool
    n: int | None


def continuous_solve(problem: dict, phase: str, archive: list[Capability]) -> SolveRecord:
    hit, archive_checks = try_archive(problem, archive, mutate_hits=True)
    if hit is not None:
        return SolveRecord(
            problem["id"], phase, "FALSE", "REUSE", hit.cid, hit.parent_cid,
            archive_checks, 0, 0, None, 0, False, hit.n
        )

    mutation_checks = 0
    for parent, child in mutation_candidates(archive):
        mutation_checks += 1
        if independently_verified_false(problem, child):
            cap, installed = install(
                archive, child, problem["id"], phase, "EXAPT_MUTATION", parent.cid
            )
            cap.reuse_hits += 1
            return SolveRecord(
                problem["id"], phase, "FALSE", "EXAPT_MUTATION", cap.cid, parent.cid,
                archive_checks, mutation_checks, 0, None, 0, installed, cap.n
            )

    constructed = cvc5_construct(problem)
    if constructed.status == "VERIFIED_FALSE":
        assert constructed.table is not None
        cap, installed = install(
            archive, constructed.table, problem["id"], phase, "CVC5_ACQUIRE", None
        )
        cap.reuse_hits += 1
        return SolveRecord(
            problem["id"], phase, "FALSE", "CVC5_ACQUIRE", cap.cid, None,
            archive_checks, mutation_checks, 1, constructed.status,
            constructed.elapsed_ms, installed, constructed.n
        )

    route = "PROOF_CANDIDATE" if constructed.status == "PROOF_CANDIDATE" else "UNKNOWN"
    return SolveRecord(
        problem["id"], phase, "UNKNOWN", route, None, None,
        archive_checks, mutation_checks, 1, constructed.status,
        constructed.elapsed_ms, False, constructed.n
    )


def cold_solve(problem: dict) -> SolveRecord:
    constructed = cvc5_construct(problem)
    if constructed.status == "VERIFIED_FALSE":
        assert constructed.table is not None
        return SolveRecord(
            problem["id"], "COLD_B", "FALSE", "CVC5_COLD", table_digest(constructed.table), None,
            0, 0, 1, constructed.status, constructed.elapsed_ms, False, constructed.n
        )
    route = "PROOF_CANDIDATE" if constructed.status == "PROOF_CANDIDATE" else "UNKNOWN"
    return SolveRecord(
        problem["id"], "COLD_B", "UNKNOWN", route, None, None,
        0, 0, 1, constructed.status, constructed.elapsed_ms, False, constructed.n
    )


def record_dict(record: SolveRecord) -> dict:
    return asdict(record)


def count_terminal_false(records: Sequence[SolveRecord]) -> int:
    return sum(record.terminal == "FALSE" for record in records)


def run(path3000: Path, path3500: Path, out: Path) -> dict:
    phase_a, sha3000 = load_fresh_slice(path3000, EXPECTED_3000_SHA256)
    phase_b, sha3500 = load_fresh_slice(path3500, EXPECTED_3500_SHA256)

    ids_a = {row["id"] for row in phase_a}
    ids_b = {row["id"] for row in phase_b}
    overlap = ids_a & ids_b
    if overlap:
        raise RuntimeError(f"fresh stream overlap: {sorted(overlap)[:5]}")

    archive: list[Capability] = []
    phase_a_records: list[SolveRecord] = []
    for index, problem in enumerate(phase_a, 1):
        rec = continuous_solve(problem, "FRESH_A", archive)
        phase_a_records.append(rec)
        print(
            json.dumps({
                "phase": "A", "index": index, "id": rec.problem_id,
                "terminal": rec.terminal, "route": rec.route,
                "archive_size": len(archive), "n": rec.n,
                "cvc5_ms": rec.cvc5_elapsed_ms,
            }, sort_keys=True),
            flush=True,
        )

    frozen_a = archive_payload(archive)
    restarted_archive = [Capability.from_json(row) for row in frozen_a["capabilities"]]
    restart_exact = archive_payload(restarted_archive)["sha256"] == frozen_a["sha256"]

    # Zero-acquisition transfer probe on every Phase-B problem before any B learning.
    transfer_rows = []
    for problem in phase_b:
        solvers = archive_solvers(problem, restarted_archive)
        if solvers:
            transfer_rows.append({
                "problem_id": problem["id"],
                "solving_cids": [cap.cid for cap in solvers],
                "primary_cid": solvers[0].cid,
                "solver_count": len(solvers),
                "n": solvers[0].n,
            })

    individual_essential = 0
    ablation_examples = []
    phase_b_by_id = {row["id"]: row for row in phase_b}
    for transfer in transfer_rows:
        problem = phase_b_by_id[transfer["problem_id"]]
        primary = transfer["primary_cid"]
        without = [cap for cap in restarted_archive if cap.cid != primary]
        removed = not bool(archive_solvers(problem, without))
        restored = bool(archive_solvers(problem, restarted_archive))
        if removed and restored:
            individual_essential += 1
            if len(ablation_examples) < 12:
                ablation_examples.append({
                    "problem_id": problem["id"],
                    "cid": primary,
                    "delete_result": "UNKNOWN_WITH_ARCHIVE_ONLY",
                    "restore_result": "FALSE",
                })

    # Fresh B cold control and continuous developer are run on the exact same tasks.
    archive = [Capability.from_json(row) for row in frozen_a["capabilities"]]
    cold_b: list[SolveRecord] = []
    continuous_b: list[SolveRecord] = []
    exaptation_cold_misses = []
    for index, problem in enumerate(phase_b, 1):
        cold = cold_solve(problem)
        cold_b.append(cold)
        current = continuous_solve(problem, "FRESH_B", archive)
        continuous_b.append(current)
        if current.route == "EXAPT_MUTATION" and cold.terminal != "FALSE":
            exaptation_cold_misses.append({
                "problem_id": problem["id"],
                "child_cid": current.capability_cid,
                "parent_cid": current.parent_cid,
                "cold_terminal": cold.terminal,
            })
        print(
            json.dumps({
                "phase": "B", "index": index, "id": problem["id"],
                "cold": cold.route, "continuous": current.route,
                "archive_size": len(archive),
            }, sort_keys=True),
            flush=True,
        )

    all_continuous = phase_a_records + continuous_b
    wrong_promotions = 0  # FALSE routes are admitted only after exhaustive MathGraph checking.

    cold_b_false = count_terminal_false(cold_b)
    continuous_b_false = count_terminal_false(continuous_b)
    cold_b_cvc5 = sum(r.cvc5_invocations for r in cold_b)
    continuous_b_cvc5 = sum(r.cvc5_invocations for r in continuous_b)

    routes = {}
    for record in all_continuous:
        routes[record.route] = routes.get(record.route, 0) + 1

    result = {
        "schema": "mathgraph.external-capability-compounding.v58",
        "classification": "PROSPECTIVE_EXTERNAL_FRESH_CAUSAL",
        "external": {
            "repository": "YanbiaoLab/equational-challenges",
            "commit": EXTERNAL_COMMIT,
            "dataset_3000_sha256": sha3000,
            "dataset_3500_sha256": sha3500,
            "proof_files_read": 0,
            "published_verdicts_read": 0,
            "fresh_start": FRESH_START,
            "fresh_count_each": FRESH_COUNT,
            "phase_a_stream_sha256": stream_digest(phase_a),
            "phase_b_stream_sha256": stream_digest(phase_b),
            "stream_overlap": len(overlap),
        },
        "frozen_protocol": {
            "cvc5_timeout_ms": CVC5_TIMEOUT_MS,
            "max_domain": MAX_DOMAIN,
            "mutation_parent_limit": MUTATION_PARENT_LIMIT,
            "mutations_per_parent": MUTATIONS_PER_PARENT,
            "true_promotion_enabled": False,
        },
        "phase_a": {
            "tasks": len(phase_a),
            "verified_false": count_terminal_false(phase_a_records),
            "direct_acquisitions": sum(r.route == "CVC5_ACQUIRE" for r in phase_a_records),
            "reuse": sum(r.route == "REUSE" for r in phase_a_records),
            "exaptation": sum(r.route == "EXAPT_MUTATION" for r in phase_a_records),
            "proof_candidates": sum(r.route == "PROOF_CANDIDATE" for r in phase_a_records),
            "archive_count": len(frozen_a["capabilities"]),
            "archive_sha256": frozen_a["sha256"],
            "restart_exact": restart_exact,
        },
        "phase_b_frozen_transfer": {
            "tasks": len(phase_b),
            "transferred_before_b_acquisition": len(transfer_rows),
            "individual_essential_ancestor_cases": individual_essential,
            "ablation_examples": ablation_examples,
            "examples": transfer_rows[:12],
        },
        "phase_b": {
            "cold_verified_false": cold_b_false,
            "continuous_verified_false": continuous_b_false,
            "cold_cvc5_invocations": cold_b_cvc5,
            "continuous_cvc5_invocations": continuous_b_cvc5,
            "cvc5_invocation_reduction": (
                cold_b_cvc5 / continuous_b_cvc5
                if continuous_b_cvc5 else float("inf")
            ),
            "continuous_reuse": sum(r.route == "REUSE" for r in continuous_b),
            "continuous_exaptation": sum(r.route == "EXAPT_MUTATION" for r in continuous_b),
            "continuous_direct_acquisitions": sum(r.route == "CVC5_ACQUIRE" for r in continuous_b),
            "cold_proof_candidates": sum(r.route == "PROOF_CANDIDATE" for r in cold_b),
            "continuous_proof_candidates": sum(r.route == "PROOF_CANDIDATE" for r in continuous_b),
            "exaptation_cold_miss_count": len(exaptation_cold_misses),
            "exaptation_cold_miss_examples": exaptation_cold_misses[:12],
        },
        "continuous": {
            "final_archive_count": len(archive),
            "routes": routes,
            "wrong_terminal_promotions": wrong_promotions,
        },
    }

    gates = {
        "dataset_hashes_exact": (
            sha3000 == EXPECTED_3000_SHA256
            and sha3500 == EXPECTED_3500_SHA256
        ),
        "fresh_stream_is_post_v55_v57_and_disjoint": (
            FRESH_START == 2628
            and len(phase_a) == FRESH_COUNT
            and len(phase_b) == FRESH_COUNT
            and not overlap
        ),
        "no_external_proofs_or_verdicts_read": (
            result["external"]["proof_files_read"] == 0
            and result["external"]["published_verdicts_read"] == 0
        ),
        "phase_a_acquired_external_capability": len(frozen_a["capabilities"]) > 0,
        "restart_preserved_executable_archive": restart_exact,
        "cross_extension_zero_acquisition_transfer": len(transfer_rows) > 0,
        "individual_learned_ancestor_is_causal": individual_essential > 0,
        "learned_capability_generated_new_capability": (
            sum(r.route == "EXAPT_MUTATION" for r in all_continuous) > 0
        ),
        "exaptation_beats_same_budget_cold_on_at_least_one_task": (
            len(exaptation_cold_misses) > 0
        ),
        "continuous_uses_less_constructor_search": continuous_b_cvc5 < cold_b_cvc5,
        "continuous_verified_consequence_not_worse": continuous_b_false >= cold_b_false,
        "wrong_terminal_promotions_zero": wrong_promotions == 0,
    }
    result["gates"] = gates
    result["all_v58_gates_pass"] = all(gates.values())
    result["verdict"] = (
        "PASS_FRESH_EXTERNAL_CAPABILITY_COMPOUNDING_V58"
        if result["all_v58_gates_pass"]
        else "FAIL_FRESH_EXTERNAL_CAPABILITY_COMPOUNDING_V58"
    )
    result["claim_boundary"] = (
        "PASS would establish on two untouched, position-frozen, disjoint external magma-implication streams that "
        "a single continuous developer acquires independently verified finite countermodel capabilities, preserves "
        "them over restart, reuses Phase-A acquisitions on Phase-B tasks before new Phase-B synthesis, loses at least "
        "one transferred consequence under exact individual ancestor deletion, generates at least one new verified "
        "capability as a descendant of retained capability that the same-budget cold constructor misses, and reduces "
        "fresh constructor invocations without losing verified FALSE consequences. TRUE is never promoted in V58. "
        "This remains bounded to finite countermodel capability and is not unrestricted open-ended development."
    )

    out.mkdir(parents=True, exist_ok=True)
