// Signal is an adapter receipt assertion grounded in previously recorded native results.
// It is NOT generated by this test's direct invocation of upstream binaries.
function decide(item,withdrawn=new Set()) {
 if(item.dependencies.some(d=>withdrawn.has(d))) return 'UNKNOWN_WITHDRAWN';
 if(!item.relation||!item.verified||!/^[a-f0-9]{40}$/.test(item.rev)||!item.provenance) return 'UNKNOWN';
 if(item.signal==='positive') return 'WARRANTED_BOUNDED';
 if(item.signal==='negative') return 'REJECTED_BOUNDED';
 return 'UNKNOWN';
}
function evaluate(withdrawn=[]) {
 const gone=new Set(withdrawn);
 return Object.fromEntries(evidence.map(e=>[e.id,decide(e,gone)]));
}
function diff(a,b) {return Object.keys(a).filter(k=>a[k]!==b[k]);}
