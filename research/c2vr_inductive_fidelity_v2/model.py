"""Independent finite semantics for one source-authored ACSL inductive relation.

This is a *bounded interpretation*, not a whole-integer ACSL/Verus equivalence
theorem.  Modulo-zero is explicitly totalized to the dividend so no undefined
arithmetic is silently imported into the finite experiment.
"""

from itertools import product


def _remainder(a: int, b: int) -> int:
    return a if b == 0 else a % b


def _domain(bound: int) -> range:
    if bound < 2 or bound > 32:
        raise ValueError("bound must lie in [2, 32]")
    return range(bound + 1)


def axioms_hold(relation: set[tuple[int, int, int]], bound: int) -> bool:
    """Check the *introduction* rules on a finite, totalized arithmetic model."""
    domain = _domain(bound)
    if any((n, 0, n) not in relation for n in domain):
        return False
    for a, b, d in product(domain, repeat=3):
        if (b, _remainder(a, b), d) in relation and (a, b, d) not in relation:
            return False
    return True


def least_relation(bound: int) -> set[tuple[int, int, int]]:
    """Least fixed point generated by `gcd_zero` and `gcd_succ` on [0..bound]."""
    domain = _domain(bound)
    relation = {(n, 0, n) for n in domain}
    while True:
        extension = {
            (a, b, d)
            for a, b, d in product(domain, repeat=3)
            if (b, _remainder(a, b), d) in relation
        }
        enlarged = relation | extension
        if enlarged == relation:
            return relation
        relation = enlarged


def audit_models(bound: int = 3) -> dict:
    domain = _domain(bound)
    least = least_relation(bound)
    total = set(product(domain, repeat=3))
    query = (2, 0, 1)
    if query in least or query not in total:
        raise AssertionError("predeclared witness is not separating")
    if not axioms_hold(least, bound) or not axioms_hold(total, bound):
        raise AssertionError("one purported model violates the introduction axioms")
    return {
        "verdict": "FINITE_COUNTERMODEL",
        "claim_refuted": "INTRODUCTION_AXIOMS_DETERMINE_THE_LEAST_INDUCTIVE_RELATION",
        "domain": [0, bound],
        "modulo_zero_totalization": "a % 0 := a (finite experiment only)",
        "source_least_relation_size": len(least),
        "target_compatible_total_relation_size": len(total),
        "separating_query": list(query),
        "source_query": query in least,
        "target_compatible_query": query in total,
        "both_satisfy_introduction_axioms": True,
        "universal_verus_equivalence_proof": False,
    }
