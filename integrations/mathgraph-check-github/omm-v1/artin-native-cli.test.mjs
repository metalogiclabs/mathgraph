const request=(number,source)=>({schema:'mathgraph.omm.request.v1',repository:'metalogiclabs/mathgraph',number,
  head_sha:number===239?'2f6aaba0d71f1c0b4c0db58618a8981ccd59dc17':'06f09cd5aaa866365ceb6540cd06389bd37a727c',
  base_sha:number===239?'dfd87d1e921953badedcfae21ade76bb38f5c04a':'2f6aaba0d71f1c0b4c0db58618a8981ccd59dc17',
  candidate_source_sha256:sha(source),command:'check'});
async function setup(number,source){
 const directory=await mkdtemp(join(tmpdir(),'omm-artin-test-'));
 await writeFile(join(directory,'published-exercise.lean.txt'),published);
 await writeFile(join(directory,'candidate.lean.txt'),source);
 await writeFile(join(directory,'request.json'),JSON.stringify(request(number,source)));
 await writeFile(join(directory,'lean-toolchain'),'leanprover/lean4:v4.28.0\n');
 return directory;
}
const mathlib='8f9d9cff6bd728b17a24e163c9402775d9e6a365';
const url='https://github.com/metalogiclabs/mathgraph/actions/runs/98765';

test('bounded weakened Artin trial writes a report, contracts and immutable evidence manifest',async()=>{
 const directory=await setup(239,artinStrongSource);
 try{
  const result=await qualifyArtinDirectory({directory,mathlibGit:mathlib,runUrl:url,
    run:async unit=>unit==='Candidate'?{code:0,output:''}:{code:1,output:'type mismatch'}});
  assert.equal(result.original_target,'NOT_ESTABLISHED_IN_THIS_REPLAY');
  const report=await readFile(join(directory,'output','report.md'),'utf8');
  assert.match(report,/original target not established/i);
  const receipt=JSON.parse(await readFile(join(directory,'output','native-receipt.json')));
  assert.equal(receipt.number,239);
  const manifest=JSON.parse(await readFile(join(directory,'output','manifest.json')));
  assert.equal(manifest.source_head,request(239,artinStrongSource).head_sha);
  assert.equal(manifest.native_receipt_sha256,sha(JSON.stringify(receipt)));
  const preview=JSON.parse(await readFile(join(directory,'output','app-check-preview.json')));
  assert.equal(preview.conclusion,'neutral');
  assert.match(preview.output.summary,/NOT_ESTABLISHED_IN_THIS_REPLAY|not established in this replay/i);
  assert.equal(manifest.artifact_sha256['app-check-preview.json'],sha(JSON.stringify(preview)));
 }finally{await rm(directory,{recursive:true,force:true});}
});

