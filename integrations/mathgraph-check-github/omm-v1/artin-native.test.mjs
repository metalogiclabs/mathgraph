import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {artinStrongSource,artinRepairSource} from '../mention-artin-control-v1.mjs';
import {runControlledArtinCase} from './artin-native.mjs';
import {assessOmmClaim} from './claim-admission.mjs';

const published=`import Mathlib

open Function Fintype Subgroup Ideal Polynomial Submodule Zsqrtd
open scoped BigOperators



/-Informal Statement

Let $H$ be the subgroup generated by two elements $a, b$ of a group $G$. Prove that if $a b=b a$, then $H$ is an abelian group.
-/

theorem Artin_exercise_2_2_9 {G : Type*} [Group G] {a b : G}
  (h : a * b = b * a) :
  ∀ x y : closure {x | x = a ∨ x = b}, x * y = y * x := by
  sorry
`;
const sha=x=>createHash('sha256').update(x).digest('hex');
const mathlib='8f9d9cff6bd728b17a24e163c9402775d9e6a365';
const toolchainSha=sha('leanprover/lean4:v4.28.0\n');
const strong={schema:'mathgraph.omm.request.v1',repository:'metalogiclabs/mathgraph',number:239,
  head_sha:'2f6aaba0d71f1c0b4c0db58618a8981ccd59dc17',base_sha:'dfd87d1e921953badedcfae21ade76bb38f5c04a',
  candidate_source_sha256:sha(artinStrongSource),command:'check'};
const repaired={...strong,number:240,head_sha:'06f09cd5aaa866365ceb6540cd06389bd37a727c',
  base_sha:strong.head_sha,candidate_source_sha256:sha(artinRepairSource)};
const initial={publishedSource:published,mathlibGit:mathlib,leanToolchainSha256:toolchainSha};
const withPins=({contract,receipt},request)=>{
  const contractBytes=JSON.stringify(contract),receiptBytes=JSON.stringify(receipt);
  return assessOmmClaim({request,contractBytes,expectedContractSha256:sha(contractBytes),
    receiptBytes,expectedReceiptSha256:sha(receiptBytes)});
};

test('published Artin theorem binds original Group claim; stronger CommGroup source compiles but consumer rejects',async()=>{
  const calls=[];
  const result=await runControlledArtinCase({...initial,request:strong,source:artinStrongSource,
    run:async(unit,content)=>{calls.push([unit,content]);return unit==='Candidate'?{code:0,output:''}:{code:1,output:'type mismatch'};}});
  assert.deepEqual(calls.map(x=>x[0]),['Candidate','Consumer']);
  assert.match(calls[1][1],/\[Group G\]/);
  assert.match(calls[1][1],/MathGraphConsumer\.original_target/);
  const a=withPins(result,strong);
  assert.equal(a.status,'NATIVE_RECEIPT_BOUND');
  assert.equal(a.candidate_proof,'LEAN_COMPILED');
  assert.equal(a.original_target,'NOT_ESTABLISHED_IN_THIS_REPLAY');
  assert.equal(a.intent_fidelity,'UNKNOWN');
});

test('original Group target, separate consumer and candidate axiom audit can qualify one positive replay',async()=>{
  const calls=[];
  const result=await runControlledArtinCase({...initial,request:repaired,source:artinRepairSource,
    run:async(unit,content)=>{calls.push([unit,content]);return {code:0,output:unit==='Audit'?"'Artin_exercise_2_2_9' depends on axioms: [propext]\n'MathGraphConsumer.original_target' depends on axioms: [propext]":''};}});
  assert.deepEqual(calls.map(x=>x[0]),['Candidate','Consumer','Audit']);
  assert.match(calls[2][1],/#print axioms MathGraphConsumer\.original_target/);
  assert.equal(withPins(result,repaired).original_target,'CONSUMER_ACCEPTED');
  assert.equal(withPins(result,repaired).candidate_dependence,'UNKNOWN');
});

test('missing axiom outputs and native runner errors cannot create a success',async()=>{
  for(const outcome of ['missing','error']){
    const result=await runControlledArtinCase({...initial,request:repaired,source:artinRepairSource,
      run:async(unit)=>{
        if(outcome==='error'&&unit==='Consumer')throw Error('process failed to start');
        return {code:0,output:''};
      }});
    const a=withPins(result,repaired);
    assert.notEqual(a.original_target,'CONSUMER_ACCEPTED');
    assert.equal(a.evidence_warrant,'UNKNOWN');
  }
});

test('unsupported PR heads and source content are rejected before execution',async()=>{
  for(const changed of [{request:{...strong,head_sha:'a'.repeat(40)}},
    {source:artinStrongSource+'\n#eval 1'}]){
    let invoked=0;
    await assert.rejects(()=>runControlledArtinCase({...initial,request:strong,source:artinStrongSource,...changed,
      run:async()=>{invoked++;return {code:0,output:''};}}));
    assert.equal(invoked,0);
  }
});
